/**
 * Write sitemap.xml and llms.txt from the pages that were actually built.
 *
 * The previous sitemap was hand-written and listed four URLs, with a comment
 * saying four was all the site had. That stopped being true the moment the
 * first article shipped, and a hand-maintained list of 216 pages in 29
 * languages would stop being true again within a week.
 *
 * So nothing here is authored twice. The generator walks dist/, reads the
 * canonical and hreflang links out of each prerendered page, and writes those.
 * The sitemap therefore cannot disagree with what was published: if a page did
 * not prerender it is not in the sitemap, and if its alternates are wrong they
 * are wrong in the page too, where it is visible.
 *
 * Run after `ng build`; see the "build" script in package.json.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist/arte-calendar/browser');
const ORIGIN = 'https://www.cloud-calendars.com';

/**
 * Every page under dist.
 *
 * Prerendered routes are directories holding an index.html, but not every page
 * is one: the long-form article is a hand-written file sitting at the top
 * level. Walking only index.html quietly dropped it from the sitemap while it
 * stayed live and reachable, which is the worst of both -- a real page that
 * search engines are not told about.
 *
 * index.csr.html is the client-render shell Angular emits alongside the
 * prerendered output. It is a page in no sense that matters and must never be
 * advertised.
 */
function pages(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      if (name !== 'media') pages(path, out);
    } else if (name.endsWith('.html') && name !== 'index.csr.html') {
      out.push(path);
    }
  }
  return out;
}

const attr = (html, re) => [...html.matchAll(re)];
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

const entries = [];
for (const file of pages(DIST)) {
  let html = readFileSync(file, 'utf8');
  // Pages also sends these links in HTTP headers, where the HTML base URL does not apply.
  const isCalendar = /\/calendar\/(?:bookings\/)?index\.html$/.test(file);
  const documentHtml = isCalendar
    ? html.replace(/<link\b[^>]*\brel="preload"[^>]*\bhref="[^"]*\/single-day-view\.webp"[^>]*>/g, '')
    : html;
  const normalisedHtml = documentHtml
    .replace(/(<link rel="modulepreload" href=")(chunk-[\w-]+\.js")/g, '$1/$2')
    .replace(
      /href="(https:\/\/apps\.apple\.com\/[^"]+)"/g,
      (_, url) => `href="${url.replace(/&amp;/g, '&')}"`,
    );
  if (normalisedHtml !== html) {
    html = normalisedHtml;
    writeFileSync(file, html);
  }

  // Private tools, tokenized invitation pages, and non-Google-indexed locales must stay out of the sitemap.
  if (/<meta name="(?:robots|googlebot)" content="noindex/i.test(html)) continue;

  // The canonical is what the page says its own address is. Trusting it rather
  // than deriving one from the file path means a canonical bug shows up here
  // as a wrong sitemap instead of hiding behind a plausible-looking URL.
  const canonical = html.match(/<link rel="canonical" href="([^"]+)"/)?.[1];
  if (!canonical) {
    console.warn(`  no canonical, skipped: /${relative(DIST, file)}`);
    continue;
  }

  const alternates = attr(html, /<link rel="alternate" hreflang="([^"]+)" href="([^"]+)"/g).map(
    (m) => ({ hreflang: m[1], href: m[2] }),
  );

  // Only the page that IS the canonical gets a sitemap entry. Otherwise every
  // translation would list all 29 addresses and the file would repeat itself
  // 29 times over.
  entries.push({ loc: canonical, alternates, self: canonical });
}

// One entry per canonical URL, sorted so a diff between two builds is readable.
const seen = new Set();
const urls = entries
  .filter((e) => !seen.has(e.loc) && seen.add(e.loc))
  .sort((a, b) => a.loc.localeCompare(b.loc));

const body = urls
  .map((u) => {
    const links = u.alternates
      .map(
        (a) =>
          `\n    <xhtml:link rel="alternate" hreflang="${esc(a.hreflang)}" href="${esc(a.href)}"/>`,
      )
      .join('');
    return `  <url>\n    <loc>${esc(u.loc)}</loc>${links}\n  </url>`;
  })
  .join('\n');

writeFileSync(
  join(DIST, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by tools/postbuild.mjs from the pages that were actually built.
  Do not edit: the next build overwrites it.

  Each entry is a canonical URL. Its xhtml:link alternates are copied out of
  the page's own <head>, so a language appears here only where it is published
  — four articles carry all 29 languages, twelve carry five, and the rest are
  English only. Claiming otherwise would send crawlers to pages that do not
  exist.
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${body}
</urlset>
`,
);

// A sitemap that does not parse is worth nothing, and nothing else in the build
// would notice: it is served with the right content type, at status 200, and
// looks perfectly fine to curl. Search Console reports it as "Sitemap is HTML"
// with zero pages discovered, which points nowhere near the real cause. This
// exists because a literal "--" in the XML comment above — an ordinary dash in
// English prose — silently invalidated every sitemap this generator produced.
{
  const xml = readFileSync(join(DIST, 'sitemap.xml'), 'utf8');

  // XML forbids "--" anywhere inside a comment, including in prose.
  for (const [, body] of xml.matchAll(/<!--([\s\S]*?)-->/g)) {
    if (body.includes('--')) {
      console.error('postbuild: the sitemap comment contains "--", which XML forbids');
      process.exit(1);
    }
  }

  // And let a real parser have the last word where one is installed. xmllint
  // ships with macOS and most Linux images; where it is missing we still have
  // the check above, so skip rather than fail.
  const probe = spawnSync('xmllint', ['--noout', '-'], { input: xml, encoding: 'utf8' });
  if (probe.error?.code === 'ENOENT') {
    console.warn('postbuild: xmllint not found, sitemap checked for comment syntax only');
  } else if (probe.status !== 0) {
    console.error('postbuild: sitemap is not well-formed XML');
    console.error(probe.stderr.trim().split('\n').slice(0, 4).join('\n'));
    process.exit(1);
  }
}

// llms.txt: the same list in the form a language model can read cheaply.
// An article URL has a slug after /articles/. The hubs end there, so matching
// on the segment alone would count all twenty-nine of them as articles.
const comparisons = urls.filter((u) => new URL(u.loc).pathname.startsWith('/compare/'));
const articles = urls.filter((u) => /\/articles\/[^/]+\/$/.test(u.loc));
const llms = readFileSync(join(ROOT, 'public/llms.txt'), 'utf8')
  .split('\n## Comparisons')[0]
  .split('\n## Articles')[0]
  .trimEnd();
writeFileSync(
  join(DIST, 'llms.txt'),
  `${llms}

## Comparisons

${comparisons.map((c) => `- ${c.loc}`).join('\n')}

## Articles

${articles.map((a) => `- ${a.loc}`).join('\n')}
`,
);

// Reader-friendly text from explicitly selected source-backed guides.
// This is an optional access format, not a claim of indexing or model support.
{
  const exportText = spawnSync('python3', [join(ROOT, 'tools/export-guide-text.py')], { cwd: ROOT, encoding: 'utf8' });
  if (exportText.status !== 0) {
    console.error(exportText.stderr || exportText.error || 'guide text export failed');
    process.exit(1);
  }
  console.log(exportText.stdout.trim());
}

// --------------------------------------------------------------- link check
//
// Twenty-eight broken links shipped to production before this existed: a
// locale-aware href was built by appending to a path that had no trailing
// slash, so every translated home page linked to '/japrivacy-policy/' and
// friends. Each one returned 404 and nothing complained.
//
// A prerendered site knows every address it has, so a link to one it does not
// have is a build error rather than something to find later in Search Console.
const built = new Set(
  pages(DIST).map((f) => {
    const rel = relative(DIST, f).replace(/\\/g, '/');
    return rel.endsWith('/index.html') ? `/${rel.slice(0, -'index.html'.length)}` : `/${rel}`;
  }),
);
built.add('/');

const broken = new Map();
const unslashed = new Map();
for (const file of pages(DIST)) {
  const html = readFileSync(file, 'utf8');
  for (const [, href] of html.matchAll(/href="(\/[^"#?]*)"/g)) {
    // Non-page assets are served straight from the bucket and are not in the
    // page set; only routes are checked here.
    if (/\.(js|css|xml|txt|ico|png|jpe?g|webp|avif|svg|mp4|webm|woff2?)$/.test(href)) continue;
    if (href.startsWith('/media/') || href.startsWith('/assets/')) continue;
    const target = href.endsWith('/') ? href : `${href}/`;
    if (!built.has(target) && !built.has(href)) {
      if (!broken.has(href)) broken.set(href, new Set());
      broken.get(href).add(`/${relative(DIST, file)}`);
      continue;
    }
    // The page exists, but only at the slash form, and normalising the slash
    // before the lookup above is exactly why this went unnoticed: 397 links
    // resolved, each through a 301. The canonical tags had been fixed for the
    // same reason years earlier; the links in the pages had not.
    if (href !== target && !built.has(href)) {
      if (!unslashed.has(href)) unslashed.set(href, new Set());
      unslashed.get(href).add(`/${relative(DIST, file)}`);
    }
  }
}

if (broken.size) {
  console.error(`\npostbuild: ${broken.size} internal link(s) point at pages that were not built:`);
  for (const [href, from] of broken) {
    const where = [...from].slice(0, 3).join(', ');
    const more = from.size > 3 ? ` (+${from.size - 3} more)` : '';
    console.error(`  ${href}\n      linked from ${where}${more}`);
  }
  process.exit(1);
}

if (unslashed.size) {
  console.error(`\npostbuild: ${unslashed.size} internal link(s) omit the trailing slash, so each costs a 301:`);
  for (const [href, from] of [...unslashed].slice(0, 15)) {
    const where = [...from].slice(0, 3).join(', ');
    const more = from.size > 3 ? ` (+${from.size - 3} more)` : '';
    console.error(`  ${href}\n      linked from ${where}${more}`);
  }
  if (unslashed.size > 15) console.error(`  … and ${unslashed.size - 15} more`);
  process.exit(1);
}

const withAlternates = urls.filter((u) => u.alternates.length > 1).length;
console.log(
  `postbuild: sitemap (${urls.length} urls, ${withAlternates} with alternates), ` +
    `llms.txt (${comparisons.length} comparisons, ${articles.length} articles), ${built.size} pages, every internal link resolves without a redirect`,
);
