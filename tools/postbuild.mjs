/**
 * Write sitemap.xml and llms.txt from the pages that were actually built.
 *
 * The previous sitemap was hand-written and listed four URLs, with a comment
 * saying four was all the site had. That stopped being true the moment the
 * first article shipped, and a hand-maintained list of 216 pages in 29
 * languages would stop being true again within a week.
 *
 * So nothing here is authored twice. The generator walks dist/, reads the
 * canonical and hreflang links out of each prerendered page, and writes those.
 * The sitemap therefore cannot disagree with what was published: if a page did
 * not prerender it is not in the sitemap, and if its alternates are wrong they
 * are wrong in the page too, where it is visible.
 *
 * Run after `ng build`; see the "build" script in package.json.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIST = join(ROOT, 'dist/arte-calendar/browser');
const ORIGIN = 'https://www.cloud-calendars.com';

/**
 * Every page under dist.
 *
 * Prerendered routes are directories holding an index.html, but not every page
 * is one: the long-form article is a hand-written file sitting at the top
 * level. Walking only index.html quietly dropped it from the sitemap while it
 * stayed live and reachable, which is the worst of both -- a real page that
 * search engines are not told about.
 *
 * index.csr.html is the client-render shell Angular emits alongside the
 * prerendered output. It is a page in no sense that matters and must never be
 * advertised.
 */
function pages(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      if (name !== 'media') pages(path, out);
    } else if (name.endsWith('.html') && name !== 'index.csr.html') {
      out.push(path);
    }
  }
  return out;
}

const attr = (html, re) => [...html.matchAll(re)];
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

const entries = [];
for (const file of pages(DIST)) {
  const html = readFileSync(file, 'utf8');

  // The canonical is what the page says its own address is. Trusting it rather
  // than deriving one from the file path means a canonical bug shows up here
  // as a wrong sitemap instead of hiding behind a plausible-looking URL.
  const canonical = html.match(/<link rel="canonical" href="([^"]+)"/)?.[1];
  if (!canonical) {
    console.warn(`  no canonical, skipped: /${relative(DIST, file)}`);
    continue;
  }

  const alternates = attr(html, /<link rel="alternate" hreflang="([^"]+)" href="([^"]+)"/g).map(
    (m) => ({ hreflang: m[1], href: m[2] }),
  );

  // Only the page that IS the canonical gets a sitemap entry. Otherwise every
  // translation would list all 29 addresses and the file would repeat itself
  // 29 times over.
  entries.push({ loc: canonical, alternates, self: canonical });
}

// One entry per canonical URL, sorted so a diff between two builds is readable.
const seen = new Set();
const urls = entries
  .filter((e) => !seen.has(e.loc) && seen.add(e.loc))
  .sort((a, b) => a.loc.localeCompare(b.loc));

const body = urls
  .map((u) => {
    const links = u.alternates
      .map(
        (a) =>
          `\n    <xhtml:link rel="alternate" hreflang="${esc(a.hreflang)}" href="${esc(a.href)}"/>`,
      )
      .join('');
    return `  <url>\n    <loc>${esc(u.loc)}</loc>${links}\n  </url>`;
  })
  .join('\n');

writeFileSync(
  join(DIST, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by tools/postbuild.mjs from the pages that were actually built.
  Do not edit: the next build overwrites it.

  Each entry is a canonical URL. Its xhtml:link alternates are copied out of
  the page's own <head>, so a language appears here only where it is published
  -- four articles carry all 29 languages, twelve carry five, and the rest are
  English only. Claiming otherwise would send crawlers to pages that do not
  exist.
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:xhtml="http://www.w3.org/1999/xhtml">
${body}
</urlset>
`,
);

// llms.txt: the same list in the form a language model can read cheaply.
// An article URL has a slug after /articles/. The hubs end there, so matching
// on the segment alone would count all twenty-nine of them as articles.
const articles = urls.filter((u) => /\/articles\/[^/]+\/$/.test(u.loc));
const llms = readFileSync(join(ROOT, 'public/llms.txt'), 'utf8')
  .split('\n## Articles')[0]
  .trimEnd();
writeFileSync(
  join(DIST, 'llms.txt'),
  `${llms}

## Articles

${articles.map((a) => `- ${a.loc}`).join('\n')}
`,
);

const withAlternates = urls.filter((u) => u.alternates.length > 1).length;
console.log(
  `postbuild: sitemap (${urls.length} urls, ${withAlternates} with alternates), ` +
    `llms.txt (${articles.length} articles)`,
);
